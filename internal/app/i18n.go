// hasText reports whether key exists (in English, the reference language).
func hasText(key string) bool {
	_, ok := texts["en"][key]
	return ok
}

// T returns the text for key in lang (fallback en), formatted with args.
func T(lang, key string, args ...any) string {
	m, ok := texts[lang]
	if !ok {
		m = texts["en"]
	}
	f, ok := m[key]
	if !ok {
		if f, ok = texts["en"][key]; !ok {
			f = key
		}
	}
	if len(args) == 0 {
		return f
	}
	return fmt.Sprintf(f, args...)
}
